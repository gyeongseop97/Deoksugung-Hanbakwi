import {readFileSync,writeFileSync} from "node:fs";
import {resolve} from "node:path";
import {pathToFileURL} from "node:url";
import {withObstacleScope} from "../public/layout.js";
import {buildJeongdong} from "../public/streets.js";

// Use the same Three.js version as public/index.html. The script needs no GPU.
const [file,mode]=process.argv.slice(2);
if(!file)throw Error("Usage: node scripts/bake-gyeongbok-obstacles.mjs <local Three.js module> [--check]");
const imported=await import(pathToFileURL(resolve(file)));
const T=imported.default??imported;
const context=new Proxy({
  measureText:text=>({width:String(text).length*20}),
  getImageData:(_x,_y,width,height)=>({data:new Uint8ClampedArray(width*height*4)}),
  createImageData:(width,height)=>({data:new Uint8ClampedArray(width*height*4)}),
  createLinearGradient:()=>({addColorStop(){}}),
  createRadialGradient:()=>({addColorStop(){}})
},{get:(object,key)=>object[key]??(()=>{})});
globalThis.document={createElement:()=>({width:1,height:1,getContext:()=>context})};

const scene=new T.Scene(),unitBox=new T.BoxGeometry(1,1,1);
const materials=new Map(),cylinders=new Map();
let seed=220621;
function rand(){seed=(Math.imul(seed,1664525)+1013904223)>>>0;return seed/4294967296;}
function matte(color){
  if(!materials.has(color))materials.set(color,new T.MeshStandardMaterial({color,roughness:.88}));
  return materials.get(color);
}
function shape(geometry,color,x,y,z,parent=scene){
  const mesh=new T.Mesh(geometry,matte(color));
  mesh.position.set(x,y,z);parent.add(mesh);return mesh;
}
function box(color,x,y,z,w,h,d,parent=scene){
  const mesh=shape(unitBox,color,x,y,z,parent);
  mesh.scale.set(w,h,d);return mesh;
}
function cylinder(color,x,y,z,r,h,sides=12,parent=scene,top=1){
  const key=sides+"/"+top;
  if(!cylinders.has(key))cylinders.set(key,new T.CylinderGeometry(top,1,1,sides));
  const mesh=shape(cylinders.get(key),color,x,y,z,parent);
  mesh.scale.set(r,h,r);return mesh;
}

const kit={wx:x=>x-300,wz:y=>y-225,rand,matte,shape,box,cylinder};
const colliders=[];
const north=y=>y<-650;
const {benches}=withObstacleScope(new Map(),()=>buildJeongdong(T,scene,kit),(...record)=>{
  if(north(record[1]))colliders.push(record);
});
const seatPositions=benches.filter(bench=>north(bench.y)).map(({x,y,catPerch})=>[x,y,catPerch.heading]);
const array=(name,rows)=>`export const ${name}=[\n${rows.map(row=>"  "+JSON.stringify(row)).join(",\n")}\n];\n`;
const output="// Generated by scripts/bake-gyeongbok-obstacles.mjs. Keep bench order stable for multiplayer.\n"+
  array("gyeongbokObstacles",colliders)+array("gyeongbokBenches",seatPositions);
const destination=new URL("../public/gyeongbok-obstacles.js",import.meta.url);
if(mode==="--check"){
  if(readFileSync(destination,"utf8").replaceAll("\r\n","\n")!==output)throw Error("Gyeongbokgung collision data needs to be regenerated.");
}else writeFileSync(destination,output);
console.log(`${colliders.length} Gyeongbokgung colliders and ${seatPositions.length} bench records`);
